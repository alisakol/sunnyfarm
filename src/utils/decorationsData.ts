export function getAestheticRank(score: number): AestheticRankInfo {
  let rank = AESTHETIC_RANKS[0];
  for (const r of AESTHETIC_RANKS) {
    if (score >= r.minScore) {
      rank = r;
    }
  }
  return rank;
}

export function getNextAestheticRank(score: number): { nextRank: AestheticRankInfo | null; pointsNeeded: number; progressPercent: number } {
  const currentIndex = AESTHETIC_RANKS.findIndex((r) => r.title === getAestheticRank(score).title);
  if (currentIndex < AESTHETIC_RANKS.length - 1) {
    const nextRank = AESTHETIC_RANKS[currentIndex + 1];
    const currentMin = AESTHETIC_RANKS[currentIndex].minScore;
    const pointsNeeded = Math.max(0, nextRank.minScore - score);
    const range = nextRank.minScore - currentMin;
    const progressPercent = Math.min(100, Math.max(0, Math.round(((score - currentMin) / range) * 100)));
    return { nextRank, pointsNeeded, progressPercent };
  }
  return { nextRank: null, pointsNeeded: 0, progressPercent: 100 };
}
